// Case-insensitive lookup by name or alias; optional country constraint.
export function lookupCity(name: string, iso3?: string | null): CityEntry | null {
  const key = name.trim().toLowerCase();
  if (!key) return null;
  for (const city of CITIES) {
    if (iso3 && city.iso3 !== iso3) continue;
    if (city.name.toLowerCase() === key) return city;
    if (city.aliases?.some((a) => a.toLowerCase() === key)) return city;
  }
  return null;
}
